export interface Sprite {
  name: string;
  /** '.' = background, every other char must be in `colors`. */
  rows: string[];
  colors: Record<string, string>;
}

export interface Theme {
  id: string;
  title: string;
  icon: string;
  /** Possible biome names; one is picked per biome. */
  names: string[];
  /** Map colors. */
  ground: [string, string];
  path: string;
  accent: string;
  /** Emoji decorations scattered around the biome on the map. */
  decor: string[];
  /** Colors used to fill the image background. */
  backgrounds: string[];
  /** In-level backdrop gradient. */
  sky: [string, string];
  sprites: Sprite[];
}

